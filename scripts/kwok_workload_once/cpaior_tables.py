"""Generate the CPAIOR paper's LaTeX tables and optional figures."""

import argparse
import csv
import json
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass
from fractions import Fraction
from itertools import product
from math import comb, isfinite
from pathlib import Path
from typing import Iterable


NODES = (4, 8, 16, 32)
PODS_PER_NODE = (4, 8)
PRIORITIES = (1, 2, 4)
LOADS = (90, 95, 100, 105)
BUDGETS = (1, 10, 20)
SOLVERS = ("cp_sat", "cplex")
LABELS = {"cp_sat": "CP-SAT", "cplex": "MIP (CPLEX)", "gurobi": "MIP (Gurobi)"}
SHORT_LABELS = {"cp_sat": "CP", "cplex": "MIP", "gurobi": "GRB"}
COMMENT = "% generated by scripts.kwok_workload_once.cpaior_tables -- do not edit by hand"
END = (r"\bottomrule", r"\end{tabular}")
METRICS = ("admitted_pods", "moves", "evictions")


@dataclass(frozen=True)
class Configuration:
    nodes: int
    pods_per_node: int
    priorities: int
    load: float
    budget: int


EXPECTED = {Configuration(*values) for values in product(NODES, PODS_PER_NODE, PRIORITIES, LOADS, BUDGETS)}


@dataclass(frozen=True)
class Outcome:
    runs: int
    no_call: int
    better_optimal: int
    better_feasible: int
    default_optimal: int
    no_gain: int
    solutions: int
    duration_ms: float
    additional_pods: float
    moves: float
    evictions: float

    @property
    def included(self) -> int:
        return self.runs - self.no_call

    @property
    def improved(self) -> int:
        return self.better_optimal + self.better_feasible

    @property
    def proven(self) -> int:
        return self.better_optimal + self.default_optimal

    @property
    def improvement_rate(self) -> Fraction:
        return Fraction(self.improved, self.included) if self.included else Fraction(0)

    @property
    def mean_seconds(self) -> float | None:
        return self.duration_ms / (1000 * self.solutions) if self.solutions else None


def load_results(path: Path) -> dict[Configuration, Outcome]:
    results: dict[Configuration, Outcome] = {}
    with path.open(encoding="utf-8-sig", newline="") as stream:
        for line, row in enumerate(csv.DictReader(stream), start=2):
            try:
                config = Configuration(int(row["nodes"]), int(row["pods_per_node"]),
                                       int(row["priorities"]), float(row["util"]), int(row["timeout_s"]))
                pods = int(row["total_pods"])
                if pods != config.nodes * config.pods_per_node:
                    raise ValueError("total_pods does not match the configuration")
                # The sealer stores each disruption/gain sum as a percentage of total pods.
                totals = [
                    pods / 100 * sum(float(row[f"{metric}_pct_sum_solver_{status}"])
                                     for status in ("optimal", "feasible"))
                    for metric in METRICS
                ]
                counts = [int(row[f"n_{key}"]) for key in (
                    "seeds", "default_all_running", "solver_optimal", "solver_feasible",
                    "default_optimal", "solver_failed", "solver_solution",
                )]
                duration = float(row["solver_duration_ms_sum"])
                outcome = Outcome(*counts, duration, *totals)
                if (any(count < 0 for count in counts) or outcome.runs != 100
                        or outcome.included != int(row["n_seeds_not_all_running"])
                        or outcome.included != outcome.improved + outcome.default_optimal + outcome.no_gain
                        or not outcome.proven + outcome.better_feasible <= outcome.solutions <= outcome.included
                        or duration < 0 or not all(isfinite(v) for v in [duration, *totals])):
                    raise ValueError("inconsistent counts or metrics")
                if config not in EXPECTED:
                    raise ValueError(f"unexpected configuration {config}")
                if config in results:
                    raise ValueError(f"duplicate configuration {config}")
            except (KeyError, ValueError) as exc:
                raise ValueError(f"{path}:{line}: {exc}") from exc
            results[config] = outcome
    missing = EXPECTED - results.keys()
    if missing:
        example = min(missing, key=lambda c: (c.nodes, c.pods_per_node, c.priorities, c.load, c.budget))
        raise ValueError(f"{path}: {len(missing)} missing configurations, e.g. {example}")
    return results


Dataset = dict[str, dict[Configuration, Outcome]]


def aggregate(rows: list[Outcome]) -> Outcome:
    return Outcome(**{key: sum(getattr(row, key) for row in rows) for key in Outcome.__dataclass_fields__})


def pct(numerator: int, denominator: int) -> str:
    return f"{100 * numerator / denominator:.1f}" if denominator else "--"


def mean(total: float, count: int) -> str:
    return f"{total / count:.1f}" if count else "--"


def seconds(value: float | None) -> str:
    return f"{value:.2f}" if value is not None else "--"


def tex_row(*cells: str) -> str:
    return cells[0] + "".join(" &" + (f" {cell}" if cell else "") for cell in cells[1:]) + r" \\"


def cmidrules(first: int, width: int, count: int) -> str:
    return "".join(
        rf"\cmidrule({'lr' if i < count - 1 else 'l'}){{{first + i * width}-{first + (i + 1) * width - 1}}}"
        for i in range(count)
    )


def grouped_columns(count: int, width: int, gap: int) -> str:
    return (rf" *{{{width}}}{{r}} @{{\hspace{{{gap}pt}}}}" * (count - 1)) + rf" *{{{width}}}{{r}}"


def solver_headings(data: Dataset) -> Iterable[str]:
    return (rf"\multicolumn{{3}}{{c}}{{{LABELS[solver]}}}" for solver in data)


def outcomes_table(data: Dataset) -> list[str]:
    columns = [aggregate([row for config, row in solver.items() if config.budget == budget])
               for solver in data.values() for budget in BUDGETS]
    rows = [
        r"\begin{tabular}{@{}l" + grouped_columns(len(data), 3, 10) + r"@{}}",
        r"\toprule",
        tex_row("", *solver_headings(data)),
        cmidrules(2, 3, len(data)),
        tex_row("Time budget (s)", *(str(b) for b in BUDGETS * len(data))),
    ]
    for group in (
        ((r"Better \& proven optimal", "better_optimal"), ("Better, not proven", "better_feasible"),
         ("Default proven optimal", "default_optimal"), ("No gain", "no_gain")),
        (("Improved (total)", "improved"), ("Proven optimal (total)", "proven")),
    ):
        rows.append(r"\midrule")
        rows.extend(tex_row(label, *(pct(getattr(c, key), c.included) for c in columns)) for label, key in group)
    rows.extend((r"\midrule", tex_row(r"Mean time (s)$^\dagger$", *(seconds(c.mean_seconds) for c in columns)),
                 r"\midrule"))
    for label, key in (("additional", "additional_pods"), ("relocated", "moves"), ("evicted", "evictions")):
        rows.append(tex_row(f"Improved: {label} pods", *(mean(getattr(c, key), c.improved) for c in columns)))
    rows.extend((r"\midrule", tex_row(r"\# runs", *(f"{c.included:,}".replace(",", r"\,") for c in columns))))
    return rows


def best_index(values: Iterable[Fraction | float | int | None], *, lowest: bool = False) -> int | None:
    ranked = [(i, v) for i, v in enumerate(values) if v is not None]
    if len(ranked) < 2:
        return None
    optimal = (min if lowest else max)(value for _, value in ranked)
    best = [i for i, value in ranked if value == optimal]
    return best[0] if len(best) == 1 else None


def highlight(cells: Iterable[str], best: int | None) -> Iterable[str]:
    return (rf"\textbf{{{cell}}}" if index == best else cell for index, cell in enumerate(cells))


def cluster_summary(solver: dict[Configuration, Outcome], nodes: int, budget: int) -> Outcome:
    return aggregate([row for cfg, row in solver.items() if cfg.nodes == nodes and cfg.budget == budget])


def nodes_table(data: Dataset) -> list[str]:
    count = len(data)
    rows = [
        r"\begin{tabular}{@{}r r" + grouped_columns(4, count, 8) + r"@{}}",
        r"\toprule",
        tex_row("", "", *(rf"\multicolumn{{{count}}}{{c}}{{{label}}}" for label in
                          ("Improved", "Proven opt.", "Time (s)", r"More impr.$^\ddagger$"))),
        cmidrules(3, count, 4),
        tex_row("Nodes", "Budget (s)", *(("CP", "MIP") if count == 2 else
                                         tuple(SHORT_LABELS[solver] for solver in data)) * 4),
    ]
    for nodes in NODES:
        rows.append(r"\midrule")
        for budget in BUDGETS:
            groups = [cluster_summary(solver, nodes, budget) for solver in data.values()]
            improved = highlight((pct(c.improved, c.included) for c in groups),
                                 best_index(c.improvement_rate if c.included else None for c in groups))
            proven = highlight((pct(c.proven, c.included) for c in groups),
                               best_index(Fraction(c.proven, c.included) if c.included else None for c in groups))
            duration = highlight((seconds(c.mean_seconds) for c in groups),
                                 best_index((c.mean_seconds for c in groups), lowest=True))
            wins = [0] * count
            for cfg in EXPECTED:
                if cfg.nodes != nodes or cfg.budget != budget:
                    continue
                results = [solver[cfg] for solver in data.values()]
                if all(c.included for c in results):
                    best = best_index(c.improvement_rate for c in results)
                    if best is not None:
                        wins[best] += 1
            label = rf"\multirow{{{len(BUDGETS)}}}{{*}}{{{nodes}}}" if budget == BUDGETS[0] else ""
            rows.append(tex_row(label, str(budget), *improved, *proven, *duration,
                                *highlight(map(str, wins), best_index(wins))))
    return rows


def params_table(data: Dataset) -> list[str]:
    rows = [
        r"\begin{tabular}{@{}l l r @{\hspace{10pt}}" + grouped_columns(len(data), 3, 10) + r"@{}}",
        r"\toprule",
        tex_row("", "", "", *solver_headings(data)),
        cmidrules(4, 3, len(data)),
        tex_row("", "", "No call", *(("Improved", "Proven", "No gain") * len(data))),
    ]
    for label, key, values in (("Load", "load", LOADS), ("Pods/node", "pods_per_node", PODS_PER_NODE),
                                ("Priorities", "priorities", PRIORITIES)):
        rows.append(r"\midrule")
        for index, value in enumerate(values):
            groups = [aggregate([row for cfg, row in solver.items() if cfg.budget == 10 and getattr(cfg, key) == value])
                      for solver in data.values()]
            combined_no_call = pct(sum(c.no_call for c in groups), sum(c.runs for c in groups))
            stats = [pct(count, c.included) for c in groups for count in (c.improved, c.proven, c.no_gain)]
            heading = rf"\multirow{{{len(values)}}}{{*}}{{{label}}}" if index == 0 else ""
            rows.append(tex_row(heading, str(value) + (r"\%" if key == "load" else ""), combined_no_call, *stats))
    return rows


NO_GAIN_ROWS = (
    ("Not invoked", "", False),
    (r"\texttt{FAILED}", "FAILED", False),
    (r"\texttt{UNKNOWN}", "UNKNOWN", False),
    ("Optimal, plan not enforced", "OPTIMAL", False),
    ("Feasible, plan not enforced", "FEASIBLE", False),
    ("Optimal, plan enforced", "OPTIMAL", True),
    ("Feasible, plan enforced", "FEASIBLE", True),
)


@dataclass(frozen=True)
class SeedResult:
    placement: tuple[int, ...]
    pending: int
    best: str
    status: str
    duration_ms: int | None


def load_seed_results(path: Path) -> dict[str, SeedResult]:
    results = {}
    with path.open(encoding="utf-8-sig", newline="") as stream:
        for line, row in enumerate(csv.DictReader(stream), start=2):
            try:
                seed = row["seed"]
                if not seed or seed in results:
                    raise ValueError("empty or duplicate seed")
                placement = {int(key.removeprefix("p")): int(count) for key, count in
                             (json.loads(row["running_placed_by_prio_now"] or "{}") or {}).items()}
                if placement.keys() - {1, 2, 3, 4}:
                    raise ValueError("unexpected priority level")
                attempts = json.loads(row["solver_attempts"] or "[]") or []
                if not isinstance(attempts, list) or len(attempts) > 1:
                    raise ValueError("expected at most one solver attempt per seed")
                attempt = attempts[0] if attempts else {}
                results[seed] = SeedResult(
                    tuple(placement.get(priority, 0) for priority in (4, 3, 2, 1)),
                    int(row["unscheduled_count_before"]), row["best_solver_status"],
                    attempt["status"] if attempts else "", int(attempt["duration_ms"]) if attempts else None,
                )
            except (AttributeError, KeyError, TypeError, ValueError) as exc:
                raise ValueError(f"{path}:{line}: {exc}") from exc
    if len(results) != 100:
        raise ValueError(f"{path}: expected 100 distinct seeds, found {len(results)}")
    return results


def compare(left, right) -> int:
    return (left > right) - (left < right)


def holm_sign_tests(tests: dict) -> dict:
    ranked = []
    for key, by_seed in tests.items():
        positive = sum(value > 0 for value in by_seed.values())
        negative = sum(value < 0 for value in by_seed.values())
        count = positive + negative
        tail = sum(comb(count, wins) for wins in range(min(positive, negative) + 1))
        ranked.append((min(1, 2 * tail / 2**count), key))
    adjusted = {}
    previous = 0.0
    for index, (value, key) in enumerate(sorted(ranked)):
        previous = max(previous, min(1, (len(ranked) - index) * value))
        adjusted[key] = previous
    return adjusted


def tex_count(count: int) -> str:
    return f"{count:,}".replace(",", r"\,")


def tex_pvalue(value: float) -> str:
    if value >= 0.001:
        return f"{value:.3f}".rstrip("0").rstrip(".")
    mantissa, exponent = f"{value:.2e}".split("e")
    return rf"${mantissa}\times10^{{{int(exponent)}}}$"


def appendix_tables(root: Path, mip_solver: str = "cplex",
                    cplex_comparison: Dataset | None = None) -> list[tuple[str, list[str]]]:
    csv.field_size_limit(min(sys.maxsize, 2**31 - 1))
    solvers = ("cp_sat", mip_solver)
    gains = defaultdict(Counter)
    placements = defaultdict(Counter)
    improvements = defaultdict(Counter)
    tests = defaultdict(Counter)
    mip_placements: dict[int, Counter[int]] = defaultdict(Counter)
    categories = {(status, enforced) for _, status, enforced in NO_GAIN_ROWS}
    for nodes, density, priorities, load in product(NODES, PODS_PER_NODE, PRIORITIES, LOADS):
        config = f"nodes{nodes}_pods{nodes * density}_prio{priorities}_util{load:03d}"
        reference = load_seed_results(root / "default" / config / "results.csv")
        for budget in BUDGETS:
            job = f"{config}_timeout{budget:02d}"
            cp, mip = (load_seed_results(root / "plugin" / solver.replace("_", "-") / job / "results.csv")
                       for solver in solvers)
            if not cp.keys() == mip.keys() == reference.keys():
                raise ValueError(f"{job}: seed sets differ between CP-SAT, {LABELS[mip_solver]}, and the default scheduler")
            if cplex_comparison is not None:
                cplex = load_seed_results(root / "plugin" / "cplex" / job / "results.csv")
                if cplex.keys() != mip.keys():
                    raise ValueError(f"{job}: seed sets differ between CPLEX and Gurobi")
                mip_placements[budget].update(compare(mip[seed].placement, run.placement)
                                              for seed, run in cplex.items())
            for seed, default in reference.items():
                cp_run, mip_run = cp[seed], mip[seed]
                improved = []
                for solver, run in zip(solvers, (cp_run, mip_run)):
                    included = bool(default.pending or run.pending)
                    better = included and run.best in {"OPTIMAL", "FEASIBLE"} and run.placement > default.placement
                    improved.append(better)
                    if included and not better and not (run.best == "OPTIMAL" and run.placement == default.placement):
                        category = run.status, bool(run.best)
                        if category not in categories:
                            raise ValueError(f"{job}, {solver}, seed {seed}: unexpected no-gain outcome {category}")
                        gains[solver, budget][category] += 1
                directions = {
                    "placement": compare(mip_run.placement, cp_run.placement),
                    "improvement": compare(improved[1], improved[0]),
                    "optimality": compare(mip_run.status == "OPTIMAL", cp_run.status == "OPTIMAL"),
                }
                if cp_run.duration_ms is not None and mip_run.duration_ms is not None:
                    directions["time"] = compare(cp_run.duration_ms, mip_run.duration_ms)
                for group in (0, nodes):
                    placements[budget, group][directions["placement"]] += 1
                    improvements[budget, group][directions["improvement"]] += 1
                    for measure, direction in directions.items():
                        tests[measure, budget, group][seed] += direction

    if len(tests) != 4 * len(BUDGETS) * (1 + len(NODES)):
        raise ValueError("incomplete sign-test family; check for missing paired call times")
    adjusted = holm_sign_tests(tests)
    columns = [gains[solver, budget] for solver in solvers for budget in BUDGETS]
    no_gain = [
        r"\begin{tabular}{@{}l" + grouped_columns(len(solvers), 3, 10) + r"@{}}",
        r"\toprule",
        tex_row("", *(rf"\multicolumn{{3}}{{c}}{{{LABELS[solver]}}}" for solver in solvers)),
        cmidrules(2, 3, len(solvers)),
        tex_row("Time budget (s)", *map(str, BUDGETS * len(solvers))),
        r"\midrule",
    ]
    no_gain.extend(tex_row(label, *(tex_count(column[status, enforced]) for column in columns))
                   for label, status, enforced in NO_GAIN_ROWS)
    no_gain.extend((r"\midrule", tex_row("Total", *(tex_count(sum(column.values())) for column in columns))))
    paired = [
        r"\begin{tabular}{@{}rr rrr r rr@{}}",
        r"\toprule",
        tex_row("Budget (s)", "Nodes", "CP wins", "MIP wins", "Ties", r"$p_{\rm H}$", "CP only", "MIP only"),
    ]
    for budget in BUDGETS:
        paired.append(r"\midrule")
        for group in (0, *NODES):
            placement = placements[budget, group]
            improvement = improvements[budget, group]
            paired.append(tex_row(str(budget) if not group else "", str(group) if group else "All",
                                  *(tex_count(placement[direction]) for direction in (-1, 1, 0)),
                                  tex_pvalue(adjusted["placement", budget, group]),
                                  tex_count(improvement[-1]), tex_count(improvement[1])))
    output = [("tab_no_gain", no_gain), ("tab_paired", paired)]
    if cplex_comparison is not None:
        output.append(("tab_mip_comparison", mip_comparison_table(cplex_comparison, mip_placements)))
    return output


def mip_comparison_table(data: Dataset, placements: dict[int, Counter[int]]) -> list[str]:
    rows = [
        r"\begin{tabular}{@{}r rrr rrr rrr@{}}",
        r"\toprule",
        tex_row("", r"\multicolumn{3}{c}{Gurobi}", r"\multicolumn{3}{c}{CPLEX}",
                r"\multicolumn{3}{c}{Paired placements}"),
        cmidrules(2, 3, 3),
        tex_row("Budget", *("Impr.", "Opt.", "Time") * 2, "Gurobi", "CPLEX", "Ties"),
        r"\midrule",
    ]
    for budget in BUDGETS:
        groups = [aggregate([row for config, row in data[solver].items() if config.budget == budget])
                  for solver in ("gurobi", "cplex")]
        summary = [cell for c in groups for cell in
                   (pct(c.improved, c.included), pct(c.proven, c.included), seconds(c.mean_seconds))]
        rows.append(tex_row(str(budget), *summary, *(tex_count(placements[budget][w]) for w in (1, -1, 0))))
    return rows


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        epilog="Gurobi is included automatically when results_per_combo_gurobi.csv is present.",
    )
    parser.add_argument("--results-root", type=Path, default=Path("results"), help="directory with sealed and raw per-seed CSVs")
    parser.add_argument("--out-dir", type=Path, help="directory for the LaTeX tables (default: RESULTS_ROOT/tables/cpaior)")
    parser.add_argument("--figures", action="store_true", help="also generate the two paper figures (requires Matplotlib)")
    parser.add_argument("--figures-dir", type=Path, help="figure directory (default: RESULTS_ROOT/figures/cpaior)")
    parser.add_argument("--mip", choices=("cplex", "gurobi"),
                        help="select the sole MIP comparator for the paper; Gurobi also generates the CPLEX appendix")
    args = parser.parse_args(argv)
    if args.figures_dir is not None and not args.figures:
        parser.error("--figures-dir requires --figures")
    try:
        solvers = ("cp_sat", args.mip) if args.mip else SOLVERS
        data = {solver: load_results(args.results_root / f"results_per_combo_{solver}.csv") for solver in solvers}
        gurobi_csv = args.results_root / "results_per_combo_gurobi.csv"
        if args.mip is None and gurobi_csv.exists():
            data["gurobi"] = load_results(gurobi_csv)
        comparison = None
        if args.mip == "gurobi":
            comparison = {"gurobi": data["gurobi"],
                          "cplex": load_results(args.results_root / "results_per_combo_cplex.csv")}
        appendix = appendix_tables(args.results_root, args.mip or "cplex", comparison)
        if args.figures:
            from scripts.kwok_workload_once import cpaior_figures

            cpaior_figures.generate(data, args.figures_dir or args.results_root / "figures" / "cpaior")
        out_dir = args.out_dir if args.out_dir is not None else args.results_root / "tables" / "cpaior"
        out_dir.mkdir(parents=True, exist_ok=True)
        for name, rows in (("tab_outcomes", outcomes_table(data)), ("tab_nodes", nodes_table(data)),
                           ("tab_load_ppn", params_table(data)), *appendix):
            path = out_dir / f"{name}.tex"
            body = (*rows, *END)
            if len(data) == 3 and name not in {"tab_no_gain", "tab_paired"}:
                body = (r"\resizebox{\linewidth}{!}{%", *body, "}")
            path.write_text("\n".join((COMMENT, *body, "")), encoding="utf-8")
            print(f"[ok] wrote {path}")
    except (OSError, ValueError) as exc:
        parser.exit(1, f"error: {exc}\n")
    except ModuleNotFoundError as exc:
        if exc.name != "matplotlib":
            raise
        parser.exit(1, "error: --figures requires Matplotlib (see scripts/kwok_workload_once/requirements.txt)\n")


if __name__ == "__main__":
    main()
